# Guard against negative floating variance causing math domain errors in some tiny runs.
_orig_normal_approximation = NormalApproximationStrategy.normal_approximation


def _safe_normal_approximation(self, *args, **kwargs):
    try:
        return _orig_normal_approximation(self, *args, **kwargs)
    except ValueError as e:
        if "math domain error" not in str(e):
            raise
        estimate = kwargs.get("estimate", args[0] if len(args) > 0 else 0.0)
        sample_size = kwargs.get("sample_size", args[1] if len(args) > 1 else 0)
        population_size = kwargs.get("population_size", args[2] if len(args) > 2 else 1)
        value_range = kwargs.get("value_range", kwargs.get("value_range", (0.0, 1.0)))
        if value_range is None:
            value_range = (0.0, 1.0)
        a, b = value_range
        sample_mean = estimate if population_size == 1 else (estimate / max(sample_size, 1))
        point = population_size * sample_mean
        lower = max(a * population_size, point)
        upper = min(b * population_size, point)
        return point, lower, upper


NormalApproximationStrategy.normal_approximation = _safe_normal_approximation


def _load_env_file(path: Path):
    if not path.exists():
        return
    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip()
        value = value.strip().strip("'").strip('"')
        if key and key not in os.environ:
            os.environ[key] = value


def compute_ndcg_at_k(retrieved_docs: list, expected_docs: list, k: int = 5) -> float:
    expected_set = set(expected_docs)
    relevance = [1 if doc in expected_set else 0 for doc in list(retrieved_docs)[:k]]
    dcg = sum(rel / math.log2(i + 2) for i, rel in enumerate(relevance))
    ideal_length = min(k, len(expected_set))
    ideal_relevance = [1] * ideal_length + [0] * (k - ideal_length)
    idcg = sum(rel / math.log2(i + 2) for i, rel in enumerate(ideal_relevance))
    return dcg / idcg if idcg > 0 else 0.0


def compute_rr(retrieved_docs: list, expected_docs: list) -> float:
    expected_set = set(expected_docs)
    for i, retrieved_doc in enumerate(retrieved_docs):
        if retrieved_doc in expected_set:
            return 1.0 / (i + 1)
    return 0.0


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--dataset-dir",
        type=str,
        default=str(PROJECT_ROOT / "rapidfire" / "datasets" / "echopath"),
    )
    parser.add_argument("--max-queries", type=int, default=150)
    parser.add_argument("--num-actors", type=int, default=1)
    parser.add_argument("--num-shards", type=int, default=2)
    parser.add_argument("--experiment-name", type=str, default="echopath-rag-evals")
    parser.add_argument(
        "--results-csv",
        type=str,
        default=str(PROJECT_ROOT / "rapidfire" / "results" / "echopath_rag_results.csv"),
    )
    args = parser.parse_args()

    _load_env_file(PROJECT_ROOT / ".env")

    gemini_api_key = os.getenv("GEMINI_API_KEY", "").strip()
    openai_api_key = os.getenv("OPENAI_API_KEY", "").strip()
    if not gemini_api_key and not openai_api_key:
        raise RuntimeError(
            "No generator API key found. Set GEMINI_API_KEY or OPENAI_API_KEY in .env."
        )

    dataset_dir = Path(args.dataset_dir).resolve()
    if not dataset_dir.exists():
        raise RuntimeError(f"Dataset directory not found: {dataset_dir}")

    queries_path = dataset_dir / "queries.jsonl"
    qrels_path = dataset_dir / "qrels.tsv"
    if not queries_path.exists() or not qrels_path.exists():
        raise RuntimeError("Missing queries.jsonl or qrels.tsv. Run build_rapidfire_dataset.py first.")

    dataset = load_dataset("json", data_files=str(queries_path), split="train")
    dataset = dataset.rename_columns({"text": "query", "_id": "query_id"})
    if args.max_queries > 0:
        dataset = dataset.select(range(min(args.max_queries, len(dataset))))

    qrels = pd.read_csv(str(qrels_path), sep="\t")
    qrels = qrels.rename(columns={"query-id": "query_id", "corpus-id": "corpus_id", "score": "relevance"})

    experiment = Experiment(experiment_name=args.experiment_name, mode="evals")

    # Retrieval search space (RAG knobs).
    rag_spec = RFLangChainRagSpec(
        document_loader=DirectoryLoader(
            path=str(dataset_dir),
            glob="corpus.jsonl",
            loader_cls=JSONLoader,
            loader_kwargs={
                "jq_schema": ".",
                "content_key": "text",
                "metadata_func": lambda record, metadata: {"corpus_id": int(record.get("_id"))},
                "json_lines": True,
                "text_content": False,
            },
            sample_seed=42,
        ),
        text_splitter=List(
            [
                RecursiveCharacterTextSplitter.from_tiktoken_encoder(
                    encoding_name="gpt2", chunk_size=256, chunk_overlap=32
                ),
            ]
        ),
        embedding_cls=GoogleGenerativeAIEmbeddings,
        embedding_kwargs={
            "model": os.getenv("GEMINI_EMBEDDING_MODEL", "gemini-embedding-001"),
            "google_api_key": gemini_api_key,
        },
        vector_store=None,  # FAISS default
        search_type="similarity",
        search_kwargs={"k": 8},
        reranker_cls=None,
        reranker_kwargs={},
        enable_gpu_search=False,
    )

    def preprocess_fn(batch: Dict[str, ListType], rag: RFLangChainRagSpec, prompt_manager=None) -> Dict[str, ListType]:
        all_context = rag.get_context(batch_queries=batch["query"], serialize=False)
        retrieved_documents = [[doc.metadata["corpus_id"] for doc in docs] for docs in all_context]
        serialized_context = rag.serialize_documents(all_context)
        batch["query_id"] = [int(query_id) for query_id in batch["query_id"]]
        return {
            "prompts": [
                [
                    {"role": "system", "content": "You are a career mentor for first-generation students."},
                    {
                        "role": "user",
                        "content": (
                            "Use the context to answer in concise bullet points.\n\n"
                            f"Context:\n{context}\n\nQuestion:\n{question}"
                        ),
                    },
                ]
                for question, context in zip(batch["query"], serialized_context)
            ],
            "retrieved_documents": retrieved_documents,
            **batch,
        }

    def postprocess_fn(batch: Dict[str, ListType]) -> Dict[str, ListType]:
        batch["ground_truth_documents"] = [
            qrels[qrels["query_id"] == query_id]["corpus_id"].tolist()
            for query_id in batch["query_id"]
        ]
        return batch

    def compute_metrics_fn(batch: Dict[str, ListType]) -> Dict[str, Dict[str, Any]]:
        precisions, recalls, f1_scores, ndcgs, rrs = [], [], [], [], []
        total_queries = len(batch["query"])
        for pred, gt in zip(batch["retrieved_documents"], batch["ground_truth_documents"]):
            retrieved = list(pred)
            expected = list(gt)
            retrieved_set = set(retrieved)
            expected_set = set(expected)
            true_pos = len(retrieved_set.intersection(expected_set))
            precision = true_pos / len(retrieved_set) if retrieved_set else 0.0
            recall = true_pos / len(expected_set) if expected_set else 0.0
            f1 = 2 * precision * recall / (precision + recall) if (precision + recall) > 0 else 0.0
            precisions.append(precision)
            recalls.append(recall)
            f1_scores.append(f1)
            ndcgs.append(compute_ndcg_at_k(retrieved, expected, k=5))
            rrs.append(compute_rr(retrieved, expected))
        return {
            "Total": {"value": total_queries},
            "Precision": {"value": sum(precisions) / total_queries if total_queries else 0.0},
            "Recall": {"value": sum(recalls) / total_queries if total_queries else 0.0},
            "F1 Score": {"value": sum(f1_scores) / total_queries if total_queries else 0.0},
            "NDCG@5": {"value": sum(ndcgs) / total_queries if total_queries else 0.0},
            "MRR": {"value": sum(rrs) / total_queries if total_queries else 0.0},
        }

    def accumulate_metrics_fn(aggregated_metrics: Dict[str, ListType]) -> Dict[str, Dict[str, Any]]:
        num_queries_per_batch = [m["value"] for m in aggregated_metrics["Total"]]
        total_queries = sum(num_queries_per_batch)
        algebraic_metrics = ["Precision", "Recall", "F1 Score", "NDCG@5", "MRR"]
        return {
            "Total": {"value": total_queries},
            **{
                metric: {
                    "value": (
                        sum(
                            m["value"] * queries
                            for m, queries in zip(aggregated_metrics[metric], num_queries_per_batch)
                        ) / total_queries
                    ) if total_queries else 0.0,
                    "is_algebraic": True,
                    "value_range": (0, 1),
                }
                for metric in algebraic_metrics
            },
        }

    if gemini_api_key:
        # Gemini OpenAI-compatible endpoint.
        generator_config = RFOpenAIAPIModelConfig(
            client_config={
                "api_key": gemini_api_key,
                "base_url": "https://generativelanguage.googleapis.com/v1beta/openai/",
                "max_retries": 2,
            },
            model_config={
                "model": os.getenv("GEMINI_MODEL", "gemini-2.0-flash"),
                "max_completion_tokens": 512,
            },
            rpm_limit=10_000,
            tpm_limit=2_000_000,
            rag=rag_spec,
            prompt_manager=None,
        )
    else:
        generator_config = RFOpenAIAPIModelConfig(
            client_config={
                "api_key": openai_api_key,
                "max_retries": 2,
            },
            model_config={
                "model": os.getenv("OPENAI_MODEL", "gpt-4o-mini"),
                "max_completion_tokens": 512,
            },
            rpm_limit=10_000,
            tpm_limit=2_000_000,
            rag=rag_spec,
            prompt_manager=None,
        )

    config_set = {
        "openai_config": List([generator_config]),
        "batch_size": 64,
        "preprocess_fn": preprocess_fn,
        "postprocess_fn": postprocess_fn,
        "compute_metrics_fn": compute_metrics_fn,
        "accumulate_metrics_fn": accumulate_metrics_fn,
    }
    config_group = RFGridSearch(config_set)

    print(f"Running RapidFire evals with {len(dataset)} queries...")
    results = experiment.run_evals(
        config_group=config_group,
        dataset=dataset,
        num_actors=args.num_actors,
        num_shards=args.num_shards,
        seed=42,
    )
    experiment.end()

    rows = []
    for run_id, (_, metrics_dict) in results.items():
        row = {"run_id": run_id}
        for key, val in metrics_dict.items():
            row[key] = val.get("value") if isinstance(val, dict) else val
        rows.append(row)
    df = pd.DataFrame(rows)

    results_csv = Path(args.results_csv).resolve()
    results_csv.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(results_csv, index=False)
    print(f"Saved results -> {results_csv}")

    if not df.empty and "NDCG@5" in df.columns:
        best = df.sort_values("NDCG@5", ascending=False).iloc[0]
        print("Best run:")
        print(best.to_dict())


if __name__ == "__main__":
    main()
